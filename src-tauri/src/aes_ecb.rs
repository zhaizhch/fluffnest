const RCON: [u8; 11] = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
];

fn xtime(x: u8) -> u8 {
    let x = x as u16;
    (((x << 1) ^ (((x >> 7) & 1) * 0x1b)) & 0xff) as u8
}

fn mul(x: u8, y: u8) -> u8 {
    ((x as u16 * (y & 1) as u16)
        ^ (xtime(x) as u16 * ((y >> 1) & 1) as u16)
        ^ (xtime(xtime(x)) as u16 * ((y >> 2) & 1) as u16)
        ^ (xtime(xtime(xtime(x))) as u16 * ((y >> 3) & 1) as u16)
        ^ (xtime(xtime(xtime(xtime(x)))) as u16 * ((y >> 4) & 1) as u16)) as u8
}

fn key_expansion(key: &[u8; 16]) -> [u8; 176] {
    let mut w = [0u8; 176];
    w[..16].copy_from_slice(key);
    let mut i = 16;
    let mut rcon_i = 1;
    let mut t = [0u8; 4];
    while i < 176 {
        t.copy_from_slice(&w[i - 4..i]);
        if i % 16 == 0 {
            let tmp = t[0];
            t[0] = t[1];
            t[1] = t[2];
            t[2] = t[3];
            t[3] = tmp;
            for b in &mut t {
                *b = SBOX[*b as usize];
            }
            t[0] ^= RCON[rcon_i];
            rcon_i += 1;
        }
        for j in 0..4 {
            w[i] = w[i - 16] ^ t[j];
            i += 1;
        }
    }
    w
}

fn add_round_key(state: &mut [u8; 16], rk: &[u8]) {
    for i in 0..16 {
        state[i] ^= rk[i];
    }
}

fn inv_sub_bytes(state: &mut [u8; 16]) {
    for b in state.iter_mut() {
        *b = INV_SBOX[*b as usize];
    }
}

fn inv_shift_rows(state: &mut [u8; 16]) {
    let mut t = [0u8; 16];
    t.copy_from_slice(state);
    // row 1 right 1
    state[1] = t[13];
    state[5] = t[1];
    state[9] = t[5];
    state[13] = t[9];
    // row 2 right 2
    state[2] = t[10];
    state[6] = t[14];
    state[10] = t[2];
    state[14] = t[6];
    // row 3 right 3
    state[3] = t[7];
    state[7] = t[11];
    state[11] = t[15];
    state[15] = t[3];
}

fn inv_mix_columns(state: &mut [u8; 16]) {
    for c in 0..4 {
        let i = c * 4;
        let a0 = state[i];
        let a1 = state[i + 1];
        let a2 = state[i + 2];
        let a3 = state[i + 3];
        state[i] = mul(a0, 0x0e) ^ mul(a1, 0x0b) ^ mul(a2, 0x0d) ^ mul(a3, 0x09);
        state[i + 1] = mul(a0, 0x09) ^ mul(a1, 0x0e) ^ mul(a2, 0x0b) ^ mul(a3, 0x0d);
        state[i + 2] = mul(a0, 0x0d) ^ mul(a1, 0x09) ^ mul(a2, 0x0e) ^ mul(a3, 0x0b);
        state[i + 3] = mul(a0, 0x0b) ^ mul(a1, 0x0d) ^ mul(a2, 0x09) ^ mul(a3, 0x0e);
    }
}

fn decrypt_block(block: &[u8; 16], round_keys: &[u8; 176]) -> [u8; 16] {
    let mut state = *block;
    add_round_key(&mut state, &round_keys[160..176]);
    for round in (1..10).rev() {
        inv_shift_rows(&mut state);
        inv_sub_bytes(&mut state);
        add_round_key(&mut state, &round_keys[round * 16..(round + 1) * 16]);
        inv_mix_columns(&mut state);
    }
    inv_shift_rows(&mut state);
    inv_sub_bytes(&mut state);
    add_round_key(&mut state, &round_keys[0..16]);
    state
}

pub fn aes128_ecb_decrypt(cipher: &[u8], key: &[u8; 16]) -> Result<Vec<u8>, String> {
    if cipher.is_empty() {
        return Err("密文为空".into());
    }
    if cipher.len() % 16 != 0 {
        return Err(format!("密文长度非整块: {}", cipher.len()));
    }
    let rk = key_expansion(key);
    let mut out = Vec::with_capacity(cipher.len());
    for chunk in cipher.chunks_exact(16) {
        let mut block = [0u8; 16];
        block.copy_from_slice(chunk);
        out.extend_from_slice(&decrypt_block(&block, &rk));
    }
    // PKCS7 unpad
    let pad = *out.last().unwrap_or(&0) as usize;
    if pad == 0 || pad > 16 || out.len() < pad {
        return Err("PKCS7 填充无效".into());
    }
    if !out[out.len() - pad..].iter().all(|&b| b as usize == pad) {
        return Err("PKCS7 填充无效".into());
    }
    out.truncate(out.len() - pad);
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn roundtrip_known_vector() {
        // Encrypt "Hello, FluffNest!!" (18 bytes) with PKCS7 using openssl-compatible expectations:
        // Use a known plaintext shorter than one block.
        let key = *b"0123456789abcdef";
        // Manually build one padded block: "HelloWorld!!!!!" + 0x01? Better use encrypt via reverse test.
        // NIST-like: decrypt ciphertext produced offline.
        // plaintext = "YELLOW SUBMARINE" (16 bytes) → pad of 16 bytes of 0x10 for empty next? 
        // Use plaintext "hello fluffnest" (15) + pad 0x01
        let mut pt = b"hello fluffnest".to_vec();
        pt.push(0x01);
        assert_eq!(pt.len(), 16);
        // For test we only verify decrypt of our own encrypt via double inverse isn't available.
        // Instead encrypt with a tiny ECB encrypt helper for the test.
        let ct = aes128_ecb_encrypt_for_test(&pt, &key);
        let got = aes128_ecb_decrypt(&ct, &key).expect("decrypt");
        assert_eq!(got, b"hello fluffnest");
    }

    fn aes128_ecb_encrypt_for_test(plain_padded: &[u8], key: &[u8; 16]) -> Vec<u8> {
        // Minimal encrypt for unit test only.
        fn sub_bytes(state: &mut [u8; 16]) {
            for b in state.iter_mut() {
                *b = SBOX[*b as usize];
            }
        }
        fn shift_rows(state: &mut [u8; 16]) {
            let t = *state;
            state[1] = t[5];
            state[5] = t[9];
            state[9] = t[13];
            state[13] = t[1];
            state[2] = t[10];
            state[6] = t[14];
            state[10] = t[2];
            state[14] = t[6];
            state[3] = t[15];
            state[7] = t[3];
            state[11] = t[7];
            state[15] = t[11];
        }
        fn mix_columns(state: &mut [u8; 16]) {
            for c in 0..4 {
                let i = c * 4;
                let a0 = state[i];
                let a1 = state[i + 1];
                let a2 = state[i + 2];
                let a3 = state[i + 3];
                state[i] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
                state[i + 1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
                state[i + 2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
                state[i + 3] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3);
            }
        }
        let rk = key_expansion(key);
        let mut out = Vec::new();
        for chunk in plain_padded.chunks_exact(16) {
            let mut state = [0u8; 16];
            state.copy_from_slice(chunk);
            add_round_key(&mut state, &rk[0..16]);
            for round in 1..10 {
                sub_bytes(&mut state);
                shift_rows(&mut state);
                mix_columns(&mut state);
                add_round_key(&mut state, &rk[round * 16..(round + 1) * 16]);
            }
            sub_bytes(&mut state);
            shift_rows(&mut state);
            add_round_key(&mut state, &rk[160..176]);
            out.extend_from_slice(&state);
        }
        out
    }
}
